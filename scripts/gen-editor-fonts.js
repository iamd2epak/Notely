// Generates src/editor/fontData.js: Plus Jakarta Sans as base64 so the note editor
// (which runs in a WebView) uses the app font fully offline.
// Run: node scripts/gen-editor-fonts.js
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'node_modules', '@expo-google-fonts', 'plus-jakarta-sans');
const weights = { 400: '400Regular', 700: '700Bold', 800: '800ExtraBold' };
const lines = ['// Generated by scripts/gen-editor-fonts.js. Do not edit.', 'export default {'];
for (const [w, name] of Object.entries(weights)) {
  const b64 = fs.readFileSync(path.join(dir, name, `PlusJakartaSans_${name}.ttf`)).toString('base64');
  lines.push(`  ${w}: '${b64}',`);
}
lines.push('};', '');
fs.writeFileSync(path.join(__dirname, '..', 'src', 'editor', 'fontData.js'), lines.join('\n'));
